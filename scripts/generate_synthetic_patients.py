#!/usr/bin/env python3
"""
FedNexus — Reproducible Synthetic Patient Dataset Generator
Generates clinical diagnostic records adhering strictly to the 12-dimensional
ClinicalRiskMLP feature specifications.

Field Meanings and Reference Ranges:
- external_ref: Non-identifying synthetic reference ID (e.g. SYN-PT-10042)
- client_id: Identifier of the hospital node holding the local partition (e.g. client-alpha)
- age: Patient age in years [20 - 90]
- sex: Biological sex categorization ['M', 'F']
- systolic_bp: Systolic Blood Pressure in mmHg [90 - 200]
- diastolic_bp: Diastolic Blood Pressure in mmHg [60 - 120]
- fasting_glucose: Fasting Blood Glucose in mg/dL [70 - 300]
- cholesterol: Serum Total Cholesterol in mg/dL [120 - 350]
- hdl_ldl_ratio: High-Density to Low-Density Lipoprotein Ratio [0.2 - 2.5]
- bmi: Body Mass Index (weight in kg / (height in m)^2) [18.0 - 45.0]
- troponin: High-Sensitivity Cardiac Troponin I in ng/mL [0.01 - 2.5]
- creatinine: Serum Creatinine in mg/dL [0.5 - 4.0]
- crp: C-Reactive Protein (systemic inflammation) in mg/L [0.1 - 20.0]
- resting_hr: Resting Heart Rate in beats per minute [50 - 120]
- spo2: Peripheral Blood Oxygen Saturation in % [88.0 - 100.0]
- risk_label: Binary ground truth (0 = Low/Moderate Risk, 1 = High Critical Risk)
"""

import argparse
import csv
import os
import sys
import numpy as np

def generate_records(count: int, client_id: str = "client-alpha", start_id: int = 20000, seed: int = 42):
    np.random.seed(seed)
    records = []
    
    for i in range(count):
        curr_id = start_id + i
        age = int(np.clip(np.random.normal(58, 12), 20, 88))
        sex = np.random.choice(["M", "F"], p=[0.51, 0.49])
        
        sbp = round(float(np.clip(np.random.normal(130, 18), 90, 195)), 1)
        dbp = round(float(np.clip(np.random.normal(82, 10), 60, 115)), 1)
        glucose = round(float(np.clip(np.random.normal(112, 28), 70, 290)), 1)
        chol = round(float(np.clip(np.random.normal(210, 35), 125, 340)), 1)
        ratio = round(float(np.clip(np.random.normal(1.1, 0.3), 0.3, 2.5)), 2)
        bmi = round(float(np.clip(np.random.normal(27.4, 4.5), 18.5, 43.0)), 1)
        troponin = round(float(np.clip(np.random.exponential(0.06), 0.01, 2.2)), 3)
        creatinine = round(float(np.clip(np.random.normal(1.05, 0.35), 0.5, 3.8)), 2)
        crp = round(float(np.clip(np.random.exponential(2.5), 0.2, 18.0)), 2)
        hr = int(np.clip(np.random.normal(74, 11), 52, 115))
        spo2 = round(float(np.clip(np.random.normal(97.2, 1.8), 89.0, 100.0)), 1)
        
        # Ground-truth clinical risk score
        z = (
            0.45 * (age - 55.0) / 15.0 +
            0.60 * (sbp - 125.0) / 20.0 +
            0.35 * (dbp - 80.0) / 12.0 +
            0.55 * (glucose - 100.0) / 30.0 +
            0.40 * (chol - 200.0) / 40.0 +
            -0.50 * (ratio - 1.0) / 0.4 +
            0.38 * (bmi - 26.0) / 5.0 +
            0.85 * (troponin - 0.04) / 0.1 +
            0.42 * (creatinine - 1.0) / 0.3 +
            0.48 * (crp - 2.0) / 2.5 +
            0.25 * (hr - 72.0) / 12.0 +
            -0.65 * (spo2 - 98.0) / 2.0
        )
        prob = 1.0 / (1.0 + np.exp(-z))
        risk_label = 1 if prob >= 0.50 else 0
        
        records.append({
            "external_ref": f"SYN-PT-{curr_id}",
            "client_id": client_id,
            "age": age,
            "sex": sex,
            "systolic_bp": sbp,
            "diastolic_bp": dbp,
            "fasting_glucose": glucose,
            "cholesterol": chol,
            "hdl_ldl_ratio": ratio,
            "bmi": bmi,
            "troponin": troponin,
            "creatinine": creatinine,
            "crp": crp,
            "resting_hr": hr,
            "spo2": spo2,
            "risk_label": risk_label,
            "notes": "Generated by FedNexus reproducible clinical synthesis script."
        })
        
    return records

def main():
    parser = argparse.ArgumentParser(description="FedNexus Synthetic Patient Dataset Generator")
    parser.add_argument("--count", type=int, default=50, help="Number of records to generate (default: 50)")
    parser.add_argument("--client", type=str, default="client-alpha", help="Target client node ID (default: client-alpha)")
    parser.add_argument("--output", type=str, default="synthetic_patients.csv", help="Output CSV path")
    parser.add_argument("--seed", type=int, default=101, help="Random seed for reproducibility")
    args = parser.parse_args()
    
    records = generate_records(count=args.count, client_id=args.client, seed=args.seed)
    
    headers = [
        "external_ref", "client_id", "age", "sex", "systolic_bp", "diastolic_bp",
        "fasting_glucose", "cholesterol", "hdl_ldl_ratio", "bmi", "troponin",
        "creatinine", "crp", "resting_hr", "spo2", "risk_label", "notes"
    ]
    
    with open(args.output, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=headers)
        writer.writeheader()
        writer.writerows(records)
        
    print(f"Generated {len(records)} synthetic patient records saved to {args.output}")

if __name__ == "__main__":
    main()
